def test_one_line_per_analyte_merging_its_waits(uk):
    found, _ = texts(blood() + [item("esculab", ESCULAB_PSA, "Онкологічний ризик у чоловіків", params=["ПСА загальний"])])
    # The lab lists the biopsy among the 7 days, and «до 3-х тижнів» is how long PSA stays high, not a wait.
    assert section(found, "tests") == ["ПСА: 7 днів після обстеження чи масажу простати; 2 дні без статевих контактів."]
    found, _ = texts(blood("synevo") + [item("synevo", SYNEVO_PSA, "Пакет №7 (ПСА)")])
    assert section(found, "tests") == [
        "ПСА: 7 днів після обстеження чи масажу простати, 3 тижні після біопсії; 48 год без статевих контактів, "
        "3 дні без сауни і велосипеда."]
    # Cycling is not "hard exercise" for three days.
    assert "За 12 год до аналізу: без алкоголю, паління, навантажень і стресу." in section(found, "general")


def test_the_record_s_sex_and_age_decide_which_lines_show(uk):
    plan = blood() + [item("esculab", ESCULAB_FOLLICLE, "Пакет №16. Оцінка фолікулінової фази", params=["Пролактин"]),
                      item("esculab", ESCULAB_URINE_ACR, "Альбумін-креатинінове співвідношення в сечі", ["сеча"])]
    found, man = texts(plan, sex="M")
    assert "Пролактин: не пізніше ніж через 2 год після пробудження." in section(found, "tests")
    assert not any(line.startswith("Жінкам") or "менструац" in line or "Дітям" in line for line in man)
    _, woman = texts(plan, sex="F")
    assert "Жінкам: на 2-5 день циклу, якщо лікар не призначив інше." in woman
    # «впродовж 5-7 днів після цистоскопії» is not a wait after menstruation.
    assert "Жінкам: не під час менструації." in woman
    found, child = texts(plan, sex=None, adult=False)
    assert "Немовлятам: якомога довша перерва між останнім годуванням і забором." in section(found, "general")
    assert "Дітям до 5 років: негазована вода порціями по 150-200 мл протягом 30 хв перед забором." in child
    _, psa_for_woman = texts(blood() + [item("esculab", ESCULAB_PSA, "ПСА")], sex="F")
    # The prostate sentences are a man's; the rest of the same text still applies.
    assert not any("простати" in line for line in psa_for_woman)


