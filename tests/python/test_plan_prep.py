def item(lab, prep, name, material=("сироватка крові",), params=(), covers=()):
    return {"lab": lab, "id": name, "name": name, "prep": prep, "material": list(material),
            "parameters": [{"name": p} for p in params], "covers_names": list(covers)}


def blood(lab="esculab", count=4):
    return [item(lab, ESCULAB_BLOOD if lab == "esculab" else SYNEVO_BLOOD, f"Тест {n}") for n in range(count)]


