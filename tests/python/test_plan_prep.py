def texts(items, sex="M", adult=True):
    found = testplan_prep.checklist(items, sex=sex, adult=adult, vendors={"esculab": "Esculab", "synevo": "Synevo"})
    return found, [line for group in found["groups"] for section in group["sections"] for line in section["lines"]]


def section(found, key, group=0):
    return next((s["lines"] for s in found["groups"][group]["sections"] if s["key"] == key), [])


def test_durations_read_digits_words_and_the_day_before():
    assert testplan_prep.durations("протягом 3-х діб") == [(3, 3, "d")]
    assert testplan_prep.durations("через три тижні") == [(3, 3, "w")]
    assert testplan_prep.durations("після шестигодинної перерви") == [(6, 6, "h")]
    assert testplan_prep.durations("за 1-2 дні") == [(1, 2, "d")]
    assert testplan_prep.durations("напередодні") == [(24, 24, "h")]
    assert testplan_prep.durations("через 8-12 год після прийому їжі") == [(8, 12, "h")]
    # «сім'явиверження» is not «сім» days.
    assert testplan_prep.durations("утриматись від сім'явиверження") == []


