def test_a_stricter_number_moves_to_its_own_test_and_is_never_repeated(uk):
    plan = blood(count=5) + [
        item("esculab", "Кров відбирається натщесерце (через 12 год після прийому їжі).", "Ізоферменти КФК",
             covers=["Креатинкіназа"]),
        item("esculab", ESCULAB_STOOL, "Копрограма", ["кал"])]
    found, lines = texts(plan)
    assert section(found, "general")[:2] == [
        "Натщесерце: останній прийом їжі за 8-12 год до аналізу. Чисту негазовану воду пити можна.",
        "За 24 год до аналізу: без алкоголю, паління, навантажень і стресу."]
    assert "Креатинкіназа: натщесерце 12 год." in section(found, "tests")
    # The stool test's three days without alcohol are part of its own diet line, not a second alcohol rule.
    assert section(found, "samples") == [
        "Кал: не раніше ніж через 2 тижні після колоноскопії, 3 дні дієти зі сторінки аналізу; зберіть удома, свіжий, "
        "доставте одразу."]
    assert not any("алкоголю" in line for line in lines[2:])
    assert "Копрограма: до антибіотиків чи протигрибкових або через 14 днів після курсу. Призначений курс не відкладайте: запитайте лікаря." in lines
    # One visit, one draw: the summary keeps the strictest window.
    assert found["gist"] == "Натщесерце 12 год, зразок калу"


