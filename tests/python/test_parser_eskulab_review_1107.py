def page(lines, page_number=1):
    """A native-text page from («top», "word@x0-x1 ...") lines."""
    words, text = [], []
    for top, row in sorted(lines):
        tokens = []
        for item in row.split():
            word, _, span = item.rpartition("@")
            x0, _, x1 = span.partition("-")
            words.append((float(x0), float(x1), float(top), word))
            tokens.append(word)
        text.append(" ".join(tokens))
    return {"page_number": page_number, "native_text": "\n".join(text), "ocr_text": "", "words": words}


def rows(vendor, kind, *pages):
    return {(item.page_number, item.raw_name): item for item in parse_document(vendor, kind, list(pages))}


def by_name(vendor, kind, *pages):
    return {item.raw_name: item for item in parse_document(vendor, kind, list(pages))}


