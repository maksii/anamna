def test_culture_rows_with_a_reference_column_are_read_with_their_sections_material():
    """Every row of a stool dysbacteriosis culture was lost, the abnormal ones included."""
    parsed = rows("EskuLab", "microbiology", page(CULTURES))
    # Two Lactobacillus rows on one page, one per section: the de-duplication
    # key holds the specimen, so both survive.
    lactobacilli = {
        item.specimen: item for item in parse_document("EskuLab", "microbiology", [page(CULTURES)])
        if item.raw_name == "Lactobacillus spp."
    }
    urine, stool = lactobacilli["сеча"], [lactobacilli["кал"]]
    assert (urine.value_numeric, urine.unit_raw, urine.reference_text, urine.specimen, urine.value_printed) == (
        1000.0, "КУО/мл", "Не виявлено", "сеча", "1.0 x 10^3"
    )
    assert [(item.comparator, item.value_numeric, item.value_printed) for item in stool] == [("<", 100000.0, "1.0 x 10^5")]
    bacteriuria = parsed[(1, "Ступінь бактеріурії")]
    assert (bacteriuria.value_numeric, bacteriuria.unit_raw, bacteriuria.value_printed) == (1000.0, "КУО/мл", "1,0*10^3")
    staph = parsed[(1, "Staphylococcus epidermidis")]
    assert (staph.value_numeric, staph.reference_text, staph.specimen) == (1e7, "не більше 1.0 x 10^4 КУО", "кал")
    # A power-of-ten reference is never read as the number before the caret.
    assert (staph.reference_low, staph.reference_high) == (None, None)
    absent = parsed[(1, "E.сoli із зміненими властивостями")]
    assert (absent.value_text, absent.reference_text, absent.specimen) == ("не виявлено", "в нормі <10^6", "кал")
    # The organism name wrapped onto the next line.
    assert (1, "Escherichia coli з нормальними властивостями") in parsed
    # The commentary under the urine table is no result.
    assert not [name for _, name in parsed if name.startswith("Виявлений")]


